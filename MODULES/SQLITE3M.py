import sqlite3
conn=sqlite3.connect('Employee1.db')
cursor=conn.cursor()
cursor.execute('''CREATE TABLE IF NOT EXISTS employee1(name TEXT NOT NULL, age INTEGER, desg TEXT)''')
cursor.execute('INSERT INTO employee1 VALUES("Rahul",40,"MANAGER")')
