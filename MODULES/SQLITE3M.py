def display():
    cursor.execute('SELECT * FROM employee1')
    records=cursor.fetchall()
    print("NAME\tAGE\tDESIGNATION")
    print("-"*27)
    for rows in records:
        print(f"{rows[0]}\t{rows[1]}\t{rows[2]}")
display()
